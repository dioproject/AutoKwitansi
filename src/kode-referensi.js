/** Normalisasi kode ("07.12.04." -> "07.12.04") */
export function normKode(kode) {
  return (kode || "").trim().replace(/[.\s]+$/, "");
}

/** Lookup uraian resmi kegiatan ARKAS berdasarkan kode */
export function cariUraianKegiatan(kode) {
  const k = normKode(kode);
  if (!k) return "";
  const hit = DAFTAR_KEGIATAN.find(([c]) => c === k);
  return hit ? hit[1] : "";
}
